"""LaTeX table fragments for the paper, one file per table.

    table_dataset.tex     GPU dataset build: outcomes per category and template
    table_categories.tex  Phase 5 per-category table (base / fine-tuned)
    table_search.tex      pass@1 vs best-of-4 vs best-of-4 + repair
    table_training.tex    training run: split, config, loss, wall-clock, memory
    table_rubric.tex      explanation rubric scores

The paper \\input{}s these by name and shows a red TODO where a file is
missing. So a fragment is returned ONLY when its data exists: no stub, no
empty table, nothing that could be mistaken for a result. Inside a table
that does exist, a single missing cell still reads "not run".

Preamble needed: \\usepackage{booktabs} (rules) and \\usepackage{graphicx}
(\\resizebox, used for tables wider than four columns).
"""

from __future__ import annotations

import re

from evaluation.report.artifacts import Artifacts
from evaluation.report.render import dataset_table, phase5_table, rubric_table, search_table, training_table

FRAGMENT_NAMES = ("table_dataset", "table_categories", "table_search", "table_training", "table_rubric")
PACKAGES_NOTE = "% Needs \\usepackage{booktabs} and \\usepackage{graphicx} in the preamble."
HEADER = "% Generated by python -m evaluation.report from real artifacts -- regenerate rather than edit.\n" + PACKAGES_NOTE

CELL_NOTE = ("Cells: \\% (k/n) [Wilson 95\\% interval]; $^\\dagger$ $n<20$. "
             "``not run'': no artifact for that stage.")
SPEEDUP_NOTE = ("Speedup = PyTorch reference time / kernel time on one GPU. Mean (arithmetic) and geomean "
                "(geometric) are over correct, finitely timed kernels only; fast$_1$ = correct and faster than "
                "the reference, over all attempts.")


def _tex(cell: str) -> str:
    """Escape what our cells can contain. Cells built with latex=True already escape % and use $...$,
    so only unescaped % and bare underscores outside math are touched."""
    cell = re.sub(r"(?<!\\)%", r"\\%", cell)
    if "$" not in cell:
        cell = re.sub(r"(?<!\\)_", r"\\_", cell)
    return cell.replace("×", "$\\times$").replace("–", "--")


def _table(rows: list[list[str]], caption: str, label: str, label_cols: int = 1,
           midrules_after: tuple[int, ...] = ()) -> str:
    """A booktabs table. Tables wider than four columns are scaled to \\columnwidth."""
    rows = [[_tex(c) for c in row] for row in rows]
    cols = "l" * label_cols + "r" * (len(rows[0]) - label_cols)
    body = [" & ".join(rows[0]) + " \\\\", "\\midrule"]
    for i, row in enumerate(rows[1:], 1):
        body.append(" & ".join(row) + " \\\\")
        if i in midrules_after:
            body.append("\\midrule")
    tabular = [f"\\begin{{tabular}}{{{cols}}}", "\\toprule", *body, "\\bottomrule", "\\end{tabular}"]
    if len(rows[0]) > 4:
        tabular = ["\\resizebox{\\columnwidth}{!}{%", *tabular, "}"]
    return "\n".join([HEADER, "\\begin{table}[t]", "\\centering", "\\small", *tabular,
                      f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\end{table}"]) + "\n"


def fragments(art: Artifacts) -> dict[str, str]:
    """{fragment name: LaTeX} for every table whose data exists."""
    out: dict[str, str] = {}

    # Dataset: the GPU build only. An interpreter check has no speedups and isn't the dataset.
    if art.dataset is not None and art.dataset.per_category:
        by_cat = dataset_table(art, "category")
        by_tpl = dataset_table(art, "template")
        rows = by_cat + [[r[0]] + r[1:] for r in by_tpl[1:]]
        smoke = " Smoke run (one instance per template), not the full grid." if art.dataset.smoke else ""
        out["table_dataset"] = _table(
            rows, "Dataset build: verification outcome of every generated candidate, per category (top) and "
                  f"template (bottom). OOM = out of GPU memory. Median speedup over passing kernels.{smoke}",
            "tab:dataset", midrules_after=(len(by_cat) - 1,))

    # Categories: at least one of the runs the Phase 5 table is built from.
    if art.run("base") or art.run("ft") or art.run("ft", 4, 1):
        out["table_categories"] = _table(
            phase5_table(art, latex=True),
            f"Per-category results on held-out templates. {CELL_NOTE} {SPEEDUP_NOTE}", "tab:categories")

    # Search: needs at least one search run beyond plain pass@1, else it isn't a search result.
    if any(art.run(m, nc, rr) for m in ("base", "ft") for nc, rr in ((4, 0), (4, 1))):
        out["table_search"] = _table(
            search_table(art, latex=True),
            f"Inference-time search: \\% correct for pass@1, best-of-4 and best-of-4 + 1 repair. {CELL_NOTE}",
            "tab:search", label_cols=2)

    training = training_table(art)
    if training:
        out["table_training"] = _table(training, "Fine-tuning run (values recorded by the run's artifacts; "
                                                 "``configured'' = from the config file).", "tab:training")

    rubric = rubric_table(art, latex=True)
    if rubric:
        out["table_rubric"] = _table(
            rubric, "Explanation quality, hand-scored: 2 = specific and correct, 1 = partial or generic, "
                    f"0 = wrong or missing. {CELL_NOTE}", "tab:rubric")
    return out


def combined(frags: dict[str, str]) -> str:
    """tables.tex: every fragment that exists, in a fixed order."""
    return "\n".join(frags[n] for n in FRAGMENT_NAMES if n in frags)
